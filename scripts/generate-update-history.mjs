import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const ROOT_DIR = resolve(SCRIPT_DIR, '..');
const CATALOG_PATH = resolve(ROOT_DIR, 'src/core/update-history-catalog.json');
const OUTPUT_PATH = resolve(ROOT_DIR, 'src/core/update-history.generated.ts');

export function parseGitLog(output) {
  return output
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean)
    .map((line) => {
      const [date, ...subjectParts] = line.split('\t');
      return { date, subject: subjectParts.join('\t') };
    })
    .filter(({ date, subject }) => /^\d{4}-\d{2}-\d{2}$/.test(date) && subject.length > 0);
}

function readCatalog() {
  return JSON.parse(readFileSync(CATALOG_PATH, 'utf8'));
}

function fallbackDateFor(entry, usedDates) {
  if (!usedDates.has(entry.fallbackDate)) return entry.fallbackDate;
  const date = new Date(`${entry.fallbackDate}T00:00:00Z`);
  while (usedDates.has(date.toISOString().slice(0, 10))) {
    date.setUTCDate(date.getUTCDate() - 1);
  }
  return date.toISOString().slice(0, 10);
}

export function formatGeneratedHistory(commits, catalog = readCatalog()) {
  const usedDates = new Set();
  const entries = [];
  for (const entry of catalog) {
    const matchingCommit = commits.find(({ subject }) =>
      entry.patterns.some((pattern) => subject.toLowerCase().includes(pattern.toLowerCase())),
    );
    const candidateDate = matchingCommit?.date;
    const date = candidateDate && !usedDates.has(candidateDate)
      ? candidateDate
      : fallbackDateFor(entry, usedDates);
    usedDates.add(date);
    entries.push({ date, title: entry.title, summary: entry.summary });
  }
  return entries.sort((left, right) => right.date.localeCompare(left.date));
}

function readCommits() {
  try {
    const output = execFileSync('git', ['log', '--date=short', '--format=%ad\t%s', '-80'], {
      cwd: ROOT_DIR,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    });
    return parseGitLog(output);
  } catch {
    return [];
  }
}

export function renderGeneratedModule(entries) {
  return `// Generated by scripts/generate-update-history.mjs. Do not edit manually.\nexport const GENERATED_UPDATE_HISTORY = Object.freeze(${JSON.stringify(entries, null, 2)});\n`;
}

export function generateUpdateHistory() {
  const entries = formatGeneratedHistory(readCommits());
  writeFileSync(OUTPUT_PATH, renderGeneratedModule(entries), 'utf8');
  return entries;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const entries = generateUpdateHistory();
  console.log(`Generated ${entries.length} update-history entries.`);
}
